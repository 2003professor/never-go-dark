class OursP1P2(Policy):
    name = "ours_p1p2"
    reads_messages = True
    gateway_config = {"sessions_roam": False, "recovery_mode": "reactive_rehandshake"}

    def reset(self, scenario_name, seed):
        self.ft = FeatureTracker(use_modem=USE_MODEM)
        self.low_since = None
        self.on_secondary_since = None
        self.primary_cls = None
        self.last_p = 0.0
        self.p_hist = deque(maxlen=SATCOM_RISE_WIN + 1)
        self.p_base = deque(maxlen=P_WIN)      # this primary link's recent p (adaptive threshold)

    # ---- P2 -----------------------------------------------------------------
    def _p2(self, obs, p, act):
        cur = _cls(obs.bearer_hint.current_bearer_class) if obs.bearer_hint else ""
        cand = obs.bearer_hint.candidate_available if obs.bearer_hint else None
        sb = obs.standby
        t = obs.t_s
        if self.primary_cls is None and cur:
            self.primary_cls = cur
        on_secondary = bool(self.primary_cls) and cur != self.primary_cls
        if on_secondary:
            self.on_secondary_since = self.on_secondary_since or t
        else:
            self.on_secondary_since = None

        if not on_secondary:
            self.p_base.append(p)
        if on_secondary:
            # Return to the primary once it is offered again and we have held long enough.
            held = t - self.on_secondary_since >= RETURN_HOLD_S
            if cand is not None and _cls(cand) == self.primary_cls and held:
                if sb.ready:
                    act.cutover = True
                elif not sb.warming:
                    act.warm_standby = cand
            return

        backlog = sum(q.depth_bytes for q in obs.planes)
        failing = obs.link.dpd_missed > 0 or obs.link.telemetry_age_s > KA_OVERDUE_S or \
            obs.link.loss_est > LOSS_CUT or \
            ((obs.link.tput_est_mbps or 0.0) < CUT_TPUT_MBPS and backlog > 20000)
        if cand is None:
            return
        base = statistics.median(self.p_base) if len(self.p_base) >= 30 else None
        th_warm = TH_WARM
        if base is not None:
            th_warm = min(TH_WARM, max(P_FLOOR, base + WARM_MARGIN))
        cand_cls = _cls(cand)
        if cand is not None and cand_cls in SATCOM:
            # Only grant the lowered (early) satcom threshold when p is actually
            # rising toward collapse; otherwise keep the general TH_WARM so band
            # wander does not warm the satcom leg spuriously.
            rising = (len(self.p_hist) > SATCOM_RISE_WIN and
                      p - self.p_hist[0] >= SATCOM_RISE_DELTA)
            if rising:
                th_warm = min(th_warm, TH_WARM_SATCOM_BY_CLASS.get(cand_cls, TH_WARM_SATCOM))
        if not sb.warming and not sb.ready and p >= th_warm:
            act.warm_standby = cand
        if sb.ready and (p >= TH_CUT or failing):
            act.cutover = True
            return
        if (sb.warming or sb.ready) and p < TH_LOW:
            self.low_since = self.low_since or t
            if t - self.low_since >= COOL_S:
                act.teardown_standby = True
                self.low_since = None
        else:
            self.low_since = None

    # ---- P1 -----------------------------------------------------------------
    def _p1(self, obs, p, act):
        # Freshness without thrashing: per responder keep the OLDEST queued report
        # (it may already be partly transmitted, and dropping it wastes those bytes
        # and can starve delivery entirely) and the NEWEST; drop only those in between.
        by_src = {}
        for m in obs.messages:
            if m.data_type == "pli" and m.source_id is not None:
                by_src.setdefault(m.source_id, []).append(m)
        for lst in by_src.values():
            if len(lst) > 2:
                lst.sort(key=lambda mm: mm.enqueue_t_s)
                act.drop.extend(mm.msg_id for mm in lst[1:-1])
        # Capacity proxy = recent PEAK goodput (10 s), not the instantaneous goodput:
        # capping to a fraction of delivered goodput would shrink itself every tick.
        cap = max(self.ft.tput) if self.ft.tput else 0.0
        backlog_bits = 8.0 * sum(q.depth_bytes for q in obs.planes)
        pressure = cap > 0 and backlog_bits > BACKLOG_S * cap * 1e6
        if pressure and p >= CAP_PRESSURE_P:
            act.rate_cap_mbps[3] = max(0.10, VIDEO_FRAC * cap)
            act.rate_cap_mbps[4] = max(0.05, BULK_FRAC * cap)

    def decide(self, obs):
        x = self.ft.update(obs)
        p = p_collapse(x)
        self.p_hist.append(p)
        self.last_p = p
        act = Action()
        if USE_P2:
            self._p2(obs, p, act)
        if USE_P1:
            self._p1(obs, p, act)
        if act.drop:
            act.drop = sorted(set(act.drop))
        return act


