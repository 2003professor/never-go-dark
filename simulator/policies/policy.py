def _cls(x):
    if x is None:
        return ""
    return x.value if isinstance(x, BearerClass) else str(x)


def _mode_rank(mode):
    """Coarse access-mode tier: 3 = 5G, 2 = LTE, 1 = 3G/2G, 0 = unknown/none."""
    m = (mode or "").upper()
    if m in ("5G", "CONNECTED", "NR"):
        return 3
    if m in ("LTE", "NOT_RESTRICTED", "4G"):
        return 2
    if m in ("HSPA+", "HSPA", "HSDPA", "HSUPA", "UMTS", "EDGE", "GPRS", "3G", "2G", "NONE"):
        return 1
    return 0


class FeatureTracker:
    """Features computed ONLY from the Obs stream. Shared verbatim by the offline
    trainer (predictor/train.py) so training and runtime see identical inputs."""

    NAMES = ("rtt_ms", "rtt_ratio_min20", "rtt_trend", "loss", "tput", "tput_ratio_max10",
             "tput_slope5", "telemetry_age", "dpd", "backlog_kb", "head_age_max",
             "sig", "sig_drop_max20", "sig_slope5", "sinr", "mode_rank", "mode_drop10",
             "cls_5g", "cls_lte", "cls_wifi", "cls_sub")

    def __init__(self, use_modem=True):
        self.use_modem = use_modem
        self.k = 0
        self.rtt = deque(maxlen=200)       # 20 s of keepalive RTT EWMA
        self.tput = deque(maxlen=100)      # 10 s of goodput EWMA
        self.sig = deque(maxlen=200)
        self.mode = deque(maxlen=100)

    def update(self, obs):
        self.k += 1
        L = obs.link
        if L.keepalive_rtt_ms is not None:
            self.rtt.append(L.keepalive_rtt_ms)
        self.tput.append(L.tput_est_mbps or 0.0)
        m = obs.modem if self.use_modem else None
        sig = m.signal_dbm if (m is not None and m.kind == "cellular") else None
        if sig is not None:
            self.sig.append(sig)
        self.mode.append(_mode_rank(m.access_mode) if (m is not None and m.kind == "cellular") else 0)

        rtt = L.keepalive_rtt_ms if L.keepalive_rtt_ms is not None else -1.0
        rmin = min(self.rtt) if self.rtt else None
        tput = L.tput_est_mbps if L.tput_est_mbps is not None else 0.0
        tmax = max(self.tput) if self.tput else 0.0
        t5 = list(self.tput)[-50:]
        s5 = list(self.sig)[-50:]
        cur_sig = sig if sig is not None else (self.sig[-1] if (self.sig and self.use_modem) else -140.0)
        backlog = sum(p.depth_bytes for p in obs.planes) / 1000.0
        head = max((p.head_age_s for p in obs.planes), default=0.0)
        cls = _cls(obs.bearer_hint.current_bearer_class) if obs.bearer_hint else ""
        mr = self.mode[-1] if self.mode else 0
        return (
            rtt,
            (rtt / rmin) if (rmin and rtt > 0) else 1.0,
            L.rtt_trend,
            L.loss_est,
            tput,
            (tput / tmax) if tmax > 0 else 1.0,
            (t5[-1] - t5[0]) / max(1, len(t5)) if len(t5) > 1 else 0.0,
            L.telemetry_age_s,
            float(L.dpd_missed),
            backlog,
            head,
            cur_sig,
            (max(self.sig) - cur_sig) if (self.sig and self.use_modem) else 0.0,
            (s5[-1] - s5[0]) / max(1, len(s5)) if len(s5) > 1 else 0.0,
            (m.sinr_db if (m is not None and m.sinr_db is not None) else -30.0) if self.use_modem else -30.0,
            float(mr),
            float((max(self.mode) - mr)) if self.mode else 0.0,
            1.0 if cls == "5G" else 0.0,
            1.0 if cls == "LTE" else 0.0,
            1.0 if cls == "WiFi" else 0.0,
            1.0 if cls == "cellular-subflow" else 0.0,
        )


